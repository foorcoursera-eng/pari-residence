export const hasFloor = (ent, floor) => floor >= FLOORS[ent][0] && floor <= FLOORS[ent][1];

const a100 = (area) => Math.round(area * 100);
export const typeKey = (f) => (f.studio ? 's' : String(f.rooms));
export const layoutId = (f) => typeKey(f) + '-' + a100(f.area);
export const planId = (f) => 'f' + f.rooms + '-' + a100(f.area);
export const flatId = (f) => f.ent + '-' + f.num;

/* все квартиры с производными полями */
export function allFlats() {
  return expand().map((f) => ({ ...f, id: flatId(f), layout: layoutId(f), type: typeKey(f), plan: PLANS.has(planId(f)) ? planId(f) : null }));
}

/* типы планировок: одна запись на «комнатность + площадь» */
export function layouts() {
  const map = new Map();
  allFlats().forEach((f) => {
    const L = map.get(f.layout) || { id: f.layout, type: f.type, rooms: f.rooms, studio: f.studio, area: f.area, plan: f.plan, flats: [] };
    L.flats.push(f);
    map.set(f.layout, L);
  });
  return [...map.values()].sort((a, b) => (a.type === 's' ? 0 : a.rooms) - (b.type === 's' ? 0 : b.rooms) || a.area - b.area);
}

