/* Разворачиваем сжатую запись в плоский список.
   Строка «14@78» значит: на четырнадцатом этаже квартиры начинаются с 78-го
   номера и идут подряд по списку flats. */
function expand() {
  const items = [];
  Object.keys(entrances).map(Number).sort((a, b) => a - b).forEach((ent) => {
    const e = entrances[ent];
    const studio = new Set(e.studios);
    e.tiers.forEach((tier) => {
      tier.floors.split(' ').forEach((token) => {
        const [floor, first] = token.split('@').map(Number);
        tier.flats.forEach(([rooms, area], i) => {
          items.push({
            ent,
            floor,
            num: first + i,
            rooms,
            area,
            studio: studio.has(area),
          });
        });
      });
    });
  });
  return items;
}

